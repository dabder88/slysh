from __future__ import annotations

import configparser
import json
import os
import shutil
from datetime import datetime, timezone
from http.cookiejar import MozillaCookieJar
from pathlib import Path

from slysh.paths import youtube_cookies_path, youtube_dir

COOKIES_META_NAME = "cookies-meta.json"
CHROME_APP_BOUND_HINT = (
    "Google Chrome 127+ на Windows шифрует cookies (App-Bound Encryption). "
    "Используйте Firefox или импортируйте cookies.txt вручную через расширение."
)


class YoutubeCookiesError(Exception):
    """Raised when cookies cannot be read or saved."""


def _meta_path() -> Path:
    return youtube_dir() / COOKIES_META_NAME


def _read_meta() -> dict:
    path = _meta_path()
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def _write_meta(meta: dict) -> None:
    _meta_path().write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")


def cookies_present() -> bool:
    path = youtube_cookies_path()
    return path.is_file() and path.stat().st_size > 0


def browser_cookie3_available() -> bool:
    try:
        import browser_cookie3  # noqa: F401
    except ImportError:
        return False
    return True


def cookies_status() -> dict:
    path = youtube_cookies_path()
    meta = _read_meta()
    present = cookies_present()
    updated_at = meta.get("updated_at")
    if present and not updated_at:
        try:
            updated_at = datetime.fromtimestamp(
                path.stat().st_mtime, tz=timezone.utc
            ).isoformat()
        except OSError:
            updated_at = None
    return {
        "present": present,
        "updated_at": updated_at,
        "source": meta.get("source"),
        "browser": meta.get("browser"),
        "profile": meta.get("profile"),
    }


def _write_netscape_cookies(jar) -> None:
    path = youtube_cookies_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("# Netscape HTTP Cookie File\n")
        handle.write("# Generated by Slysh\n")
        for cookie in jar:
            domain = cookie.domain or ""
            include_subdomains = "TRUE" if domain.startswith(".") else "FALSE"
            secure = "TRUE" if cookie.secure else "FALSE"
            expires = str(int(cookie.expires or 0))
            handle.write(
                "\t".join(
                    [
                        domain,
                        include_subdomains,
                        cookie.path or "/",
                        secure,
                        expires,
                        cookie.name,
                        cookie.value,
                    ]
                )
                + "\n"
            )


def import_cookies_file(source: str | Path) -> dict:
    src = Path(source)
    if not src.is_file():
        raise YoutubeCookiesError(f"Файл cookies не найден: {src}")
    dest = youtube_cookies_path()
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dest)
    now = datetime.now(timezone.utc).isoformat()
    _write_meta(
        {
            "updated_at": now,
            "source": "import",
            "browser": None,
            "profile": str(src),
        }
    )
    return cookies_status()


def _firefox_profiles() -> list[dict]:
    profiles_ini = Path(os.environ.get("APPDATA", "")) / "Mozilla" / "Firefox" / "profiles.ini"
    if not profiles_ini.is_file():
        return []
    parser = configparser.RawConfigParser()
    parser.read(profiles_ini, encoding="utf-8")
    profiles: list[dict] = []
    for section in parser.sections():
        if not section.startswith("Profile"):
            continue
        path_value = parser.get(section, "Path", fallback="").strip()
        if not path_value:
            continue
        is_relative = parser.get(section, "IsRelative", fallback="1") == "1"
        root = Path(os.environ.get("APPDATA", "")) / "Mozilla" / "Firefox"
        profile_path = (root / path_value) if is_relative else Path(path_value)
        name = parser.get(section, "Name", fallback=profile_path.name)
        cookie_db = profile_path / "cookies.sqlite"
        profiles.append(
            {
                "browser": "firefox",
                "profile": profile_path.name,
                "label": f"Firefox — {name}",
                "path": str(profile_path),
                "recommended": True,
                "warning": None,
                "cookies_available": cookie_db.is_file(),
            }
        )
    return profiles


def _chrome_profiles(browser: str, user_data: Path) -> list[dict]:
    if not user_data.is_dir():
        return []
    profiles: list[dict] = []
    local_state = user_data / "Local State"
    names: dict[str, str] = {}
    if local_state.is_file():
        try:
            payload = json.loads(local_state.read_text(encoding="utf-8"))
            info = payload.get("profile", {}).get("info_cache", {})
            if isinstance(info, dict):
                for key, value in info.items():
                    if isinstance(value, dict):
                        names[key] = str(value.get("name") or key)
        except (OSError, json.JSONDecodeError):
            pass
    for entry in sorted(user_data.iterdir()):
        if not entry.is_dir():
            continue
        if entry.name in {"System Profile", "Guest Profile"}:
            continue
        if not (entry / "Cookies").is_file() and not (entry / "Network" / "Cookies").is_file():
            continue
        label_name = names.get(entry.name, entry.name)
        cookies_available = (entry / "Network" / "Cookies").is_file() or (
            entry / "Cookies"
        ).is_file()
        profiles.append(
            {
                "browser": browser,
                "profile": entry.name,
                "label": f"{browser.title()} — {label_name}",
                "path": str(entry),
                "recommended": False,
                "warning": CHROME_APP_BOUND_HINT,
                "cookies_available": cookies_available,
            }
        )
    return profiles


def _resolve_profile_path(browser: str, profile_name: str) -> Path:
    for item in list_browser_profiles().get("profiles", []):
        if item.get("browser") == browser and item.get("profile") == profile_name:
            return Path(str(item["path"]))
    raise YoutubeCookiesError(f"Профиль не найден: {profile_name}")


def _cookie_db_path(browser: str, profile_path: Path) -> Path:
    if browser == "firefox":
        candidate = profile_path / "cookies.sqlite"
    elif browser in {"chrome", "edge"}:
        candidate = profile_path / "Network" / "Cookies"
        if not candidate.is_file():
            candidate = profile_path / "Cookies"
    else:
        raise YoutubeCookiesError(f"Браузер не поддерживается: {browser}")
    if not candidate.is_file():
        raise YoutubeCookiesError(
            f"В профиле «{profile_path.name}» нет файла cookies. "
            "Выберите другой профиль Firefox (например default-release) "
            "или загрузите cookies.txt вручную."
        )
    return candidate


def _load_browser_jar(browser: str, cookie_file: Path):
    import browser_cookie3

    cookie_path = str(cookie_file)
    if browser == "firefox":
        return browser_cookie3.firefox(cookie_file=cookie_path, domain_name="youtube.com")
    if browser == "chrome":
        return browser_cookie3.chrome(cookie_file=cookie_path, domain_name="youtube.com")
    if browser == "edge":
        return browser_cookie3.edge(cookie_file=cookie_path, domain_name="youtube.com")
    raise YoutubeCookiesError(f"Браузер не поддерживается: {browser}")


def list_browser_profiles() -> dict:
    profiles = _firefox_profiles()
    hint = None
    if not profiles:
        hint = (
            "Профили Firefox не найдены. Установите Firefox, войдите в YouTube "
            "или загрузите cookies.txt вручную."
        )
    elif not browser_cookie3_available():
        hint = (
            "Для автоизвлечения cookies установите extra youtube: "
            "uv pip install browser-cookie3 (или uv sync --extra youtube). "
            "Или загрузите cookies.txt вручную."
        )
    return {
        "profiles": profiles,
        "browser_cookie3": hint is None or bool(profiles),
        "firefox_only": True,
        "hint": hint,
    }


def extract_cookies_quick(browser: str = "firefox") -> dict:
    try:
        import browser_cookie3
    except ImportError as exc:
        raise YoutubeCookiesError(
            "Пакет browser-cookie3 не установлен. Выполните: uv pip install browser-cookie3"
        ) from exc

    browser_key = (browser or "firefox").strip().lower()
    try:
        if browser_key == "firefox":
            jar = browser_cookie3.firefox(domain_name="youtube.com")
        elif browser_key == "chrome":
            jar = browser_cookie3.chrome(domain_name="youtube.com")
        elif browser_key == "edge":
            jar = browser_cookie3.edge(domain_name="youtube.com")
        else:
            raise YoutubeCookiesError(f"Браузер не поддерживается: {browser_key}")
    except Exception as exc:
        raise YoutubeCookiesError(
            f"Не удалось прочитать cookies из {browser_key}: {exc}. "
            "Закройте браузер, войдите в YouTube и повторите."
        ) from exc

    youtube = [
        cookie
        for cookie in jar
        if cookie.domain and "youtube.com" in cookie.domain.lower()
    ]
    if not youtube:
        raise YoutubeCookiesError(
            "Cookies для youtube.com не найдены. "
            "Откройте YouTube в браузере и войдите в аккаунт."
        )

    filtered = MozillaCookieJar()
    for cookie in youtube:
        filtered.set_cookie(cookie)
    _write_netscape_cookies(filtered)
    now = datetime.now(timezone.utc).isoformat()
    _write_meta(
        {
            "updated_at": now,
            "source": "extract",
            "browser": browser_key,
            "profile": "default",
        }
    )
    return cookies_status()


def extract_cookies(browser: str, profile: str) -> dict:
    try:
        import browser_cookie3
    except ImportError as exc:
        raise YoutubeCookiesError(
            "Пакет browser-cookie3 не установлен. Выполните: uv pip install browser-cookie3"
        ) from exc

    browser_key = (browser or "").strip().lower()
    profile_name = (profile or "").strip()
    if not browser_key:
        raise YoutubeCookiesError("Укажите браузер.")
    if not profile_name or profile_name == "__default__":
        return extract_cookies_quick(browser_key)

    profile_path = _resolve_profile_path(browser_key, profile_name)
    cookie_file = _cookie_db_path(browser_key, profile_path)
    try:
        jar = _load_browser_jar(browser_key, cookie_file)
    except Exception as exc:
        raise YoutubeCookiesError(
            f"Не удалось прочитать cookies из профиля «{profile_name}»: {exc}"
        ) from exc

    youtube = [
        cookie
        for cookie in jar
        if cookie.domain and "youtube.com" in cookie.domain.lower()
    ]
    if not youtube:
        raise YoutubeCookiesError(
            "Cookies для youtube.com не найдены в выбранном профиле. "
            "Откройте YouTube в Firefox и войдите в аккаунт, затем повторите."
        )

    filtered = MozillaCookieJar()
    for cookie in youtube:
        filtered.set_cookie(cookie)
    _write_netscape_cookies(filtered)
    now = datetime.now(timezone.utc).isoformat()
    _write_meta(
        {
            "updated_at": now,
            "source": "extract",
            "browser": browser_key,
            "profile": profile_name,
        }
    )
    return cookies_status()
